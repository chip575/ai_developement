SESSION_SECONDS = 8 * 60 * 60


class PostgresConnection:
    """Compatibility layer for the parameterized SQL shared with local SQLite tests."""
    def __init__(self, conn):
        self.conn = conn

    @staticmethod
    def translate(sql):
        sql = sql.replace('?', '%s')
        if sql.lstrip().upper().startswith('INSERT OR IGNORE INTO '):
            sql = sql.replace('INSERT OR IGNORE INTO ', 'INSERT INTO ', 1).rstrip().rstrip(';') + ' ON CONFLICT DO NOTHING'
        return sql

    def execute(self, sql, params=()):
        return self.conn.execute(self.translate(sql), params)

    def executemany(self, sql, params):
        with self.conn.cursor() as cursor:
            cursor.executemany(self.translate(sql), params)

    def executescript(self, sql):
        # Schema uses plain statements without quoted semicolons.
        sql = sql.replace('id INTEGER PRIMARY KEY', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        for statement in sql.split(';'):
            if statement.strip():
                self.conn.execute(statement)


@contextmanager
def connect():
    database_url = setting('DATABASE_URL')
    if database_url:
        import psycopg
        from psycopg.rows import dict_row
        conn = psycopg.connect(database_url, row_factory=dict_row, connect_timeout=10)
        db = PostgresConnection(conn)
    else:
        path = db_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(str(path), timeout=10)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys=ON")
        db = conn
    try:
        yield db
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def hash_password(password: str, salt: bytes | None = None) -> str:
    salt = salt or secrets.token_bytes(16)
    result = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, 310_000)
    return f"pbkdf2_sha256$310000${salt.hex()}${result.hex()}"


def check_password(password: str, encoded: str) -> bool:
    try:
        name, rounds, salt, digest = encoded.split("$")
        if name != "pbkdf2_sha256":
            return False
        candidate = hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), int(rounds))
        return hmac.compare_digest(candidate.hex(), digest)
    except (ValueError, TypeError):
        return False


def init_db():
    with connect() as db:
        db.executescript("""
        CREATE TABLE IF NOT EXISTS students(id INTEGER PRIMARY KEY, name TEXT NOT NULL, department TEXT NOT NULL, admission_year INTEGER NOT NULL, curriculum TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS accounts(id INTEGER PRIMARY KEY, login_id TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL, student_id INTEGER NOT NULL UNIQUE REFERENCES students(id));
        CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY, student_id INTEGER NOT NULL REFERENCES students(id), expires_at INTEGER NOT NULL);
        CREATE TABLE IF NOT EXISTS courses(code TEXT PRIMARY KEY, name TEXT NOT NULL, category TEXT NOT NULL, credits REAL NOT NULL, source_grade INTEGER, source_semester INTEGER);
        CREATE TABLE IF NOT EXISTS course_records(id INTEGER PRIMARY KEY, student_id INTEGER NOT NULL REFERENCES students(id), course_code TEXT NOT NULL REFERENCES courses(code), academic_year INTEGER NOT NULL, semester INTEGER NOT NULL, category TEXT NOT NULL, grade TEXT NOT NULL, earned_credits REAL NOT NULL, status TEXT NOT NULL, UNIQUE(student_id,course_code,academic_year,semester));
        CREATE TABLE IF NOT EXISTS graduation_rules(id TEXT PRIMARY KEY, department TEXT NOT NULL, curriculum TEXT NOT NULL, total_credits REAL NOT NULL, source TEXT NOT NULL, UNIQUE(department,curriculum));
        CREATE TABLE IF NOT EXISTS required_courses(rule_id TEXT NOT NULL REFERENCES graduation_rules(id), course_code TEXT NOT NULL REFERENCES courses(code), category TEXT NOT NULL, PRIMARY KEY(rule_id,course_code));
        CREATE TABLE IF NOT EXISTS english_requirements(rule_id TEXT NOT NULL REFERENCES graduation_rules(id), exam_type TEXT NOT NULL, minimum_score INTEGER NOT NULL CHECK(minimum_score >= 0), source TEXT NOT NULL, PRIMARY KEY(rule_id,exam_type));
        CREATE TABLE IF NOT EXISTS student_english_scores(id INTEGER PRIMARY KEY, student_id INTEGER NOT NULL REFERENCES students(id), exam_type TEXT NOT NULL, score INTEGER NOT NULL CHECK(score >= 0), taken_on TEXT NOT NULL, valid_until TEXT NOT NULL, approval_status TEXT NOT NULL CHECK(approval_status IN ('approved','pending','rejected')), UNIQUE(student_id,exam_type,taken_on));
        """)


def login(login_id: str, password: str) -> tuple[str, dict] | None:
    with connect() as db:
        row = db.execute("SELECT a.password_hash,s.* FROM accounts a JOIN students s ON s.id=a.student_id WHERE a.login_id=?", (login_id,)).fetchone()
        if not row or not check_password(password, row["password_hash"]):
            return None
        token = secrets.token_urlsafe(32)
        token_hash = hashlib.sha256(token.encode()).hexdigest()
        db.execute("DELETE FROM sessions WHERE expires_at < ?", (int(time.time()),))
        db.execute("INSERT INTO sessions VALUES (?,?,?)", (token_hash, row["id"], int(time.time()) + SESSION_SECONDS))
        return token, {k: row[k] for k in ("id", "name", "department", "admission_year", "curriculum")}


def session_user(token: str | None) -> dict | None:
    if not token or len(token) > 256:
        return None
    token_hash = hashlib.sha256(token.encode()).hexdigest()
    with connect() as db:
        row = db.execute("SELECT s.* FROM sessions x JOIN students s ON s.id=x.student_id WHERE x.token_hash=? AND x.expires_at>?", (token_hash, int(time.time()))).fetchone()
        return dict(row) if row else None


def logout(token: str | None):
    if token and len(token) <= 256:
        with connect() as db:
            db.execute("DELETE FROM sessions WHERE token_hash=?", (hashlib.sha256(token.encode()).hexdigest(),))


def my_record(user_id: int) -> dict:
    with connect() as db:
        user = db.execute("SELECT * FROM students WHERE id=?", (user_id,)).fetchone()
        if not user:
            raise ValueError("학생 정보를 확인할 수 없습니다.")
        rows = db.execute("SELECT r.course_code,c.name,r.category,r.academic_year,r.semester,r.grade,r.earned_credits,r.status FROM course_records r JOIN courses c ON c.code=r.course_code WHERE r.student_id=? ORDER BY r.academic_year,r.semester,c.code", (user_id,)).fetchall()
    # No implicit equivalence mapping: latest recorded attempt is the conservative demo rule.
    latest = {}
    for row in rows:
        latest[row["course_code"]] = dict(row)
    accepted = [x for x in latest.values() if x["status"] == "이수" and x["grade"].upper() not in {"F", "U", "W"} and x["earned_credits"] > 0]
    return {"student": dict(user), "records": list(map(dict, rows)), "recognized": accepted, "total_credits": sum(x["earned_credits"] for x in accepted), "note": "데모의 동일 과목 최신 기록 기준이며, 대체과목·공식 인정 여부는 학교 확인이 필요합니다."}


def graduation(user_id: int) -> dict:
    record = my_record(user_id)
    student = record["student"]
    with connect() as db:
        # One shared MVP rule, independent of the student's admission year.
        rule = db.execute("SELECT * FROM graduation_rules WHERE id=? AND department=?", ("business-2021-demo", student["department"])).fetchone()
        if not rule:
            return {"error": "적용 교육과정의 검증된 기준을 찾지 못했습니다. 학과에 확인해 주세요."}
        required = db.execute("SELECT r.category,c.code,c.name,c.credits FROM required_courses r JOIN courses c ON c.code=r.course_code WHERE r.rule_id=? ORDER BY r.category,c.name", (rule["id"],)).fetchall()
        english_rule = db.execute("SELECT exam_type,minimum_score,source FROM english_requirements WHERE rule_id=? AND exam_type='TOEIC'", (rule["id"],)).fetchone()
        english_scores = db.execute("SELECT exam_type,score,taken_on,valid_until,approval_status FROM student_english_scores WHERE student_id=? AND exam_type='TOEIC' ORDER BY score DESC,taken_on DESC", (user_id,)).fetchall()
    return check_pnu_biz_graduation(record=record, rule=dict(rule), required_courses=[dict(row) for row in required], english_rule=dict(english_rule) if english_rule else None, english_scores=[dict(row) for row in english_scores])
